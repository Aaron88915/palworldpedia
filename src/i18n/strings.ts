// === 类型（帕鲁/工作）双语表 ===
// 已有 PAL_TYPES / WORK_SUITABILITIES 在 config.ts（带 zh/en 字段），直接用

/**
 * 根据 id 取类型 / 工作的本地化名称
 * @param id 类型 id（'fire' 等）或 工作 id（'mining' 等）
 * @param lang 'zh' | 'en'
 * @param dict 类型/工作字典
 */
export function localize(
  id: string,
  lang: Locale,
  dict: ReadonlyArray<{ id: string; zh: string; en: string }>,
): string {
  const found = dict.find((d) => d.id === id);
  if (!found) return id;
  return lang === 'zh' ? found.zh : found.en;
}
